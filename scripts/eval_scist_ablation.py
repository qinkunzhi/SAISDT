def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate and export SCIST main-ablation artifacts.")
    parser.add_argument("--ckpt", type=str, required=True)
    parser.add_argument("--out_dir", type=str, required=True)
    parser.add_argument("--low_root", type=str, default="")
    parser.add_argument("--gt_root", type=str, default="")
    parser.add_argument("--high_root", type=str, default="")
    parser.add_argument("--scist_imf_ckpt", type=str, default="")
    parser.add_argument("--scist_priors", type=str, default="")
    parser.add_argument("--scist_ablation", type=str, default="")
    parser.add_argument("--batch_size", type=int, default=1)
    parser.add_argument("--num_workers", type=int, default=0)
    parser.add_argument("--gpu", type=int, default=0)
    parser.add_argument("--device", type=str, default="cuda")
    parser.add_argument("--max_eval_batches", type=int, default=0)
    parser.add_argument("--sample_ids", type=str, default="", help="Comma-separated image basenames/stems fixed before ablation comparison.")
    parser.add_argument("--save_visual_max", type=int, default=3)
    parser.add_argument("--metric_decimals", type=int, default=4)
    parser.add_argument("--skip_no_ref_metrics", type=int, default=0)
    parser.add_argument(
        "--eval_size",
        type=int,
        default=0,
        help="Evaluation side length. 0 preserves each image's original resolution and aspect ratio (recommended).",
    )
    parser.add_argument("--eval_amp", type=int, default=1, help="Use CUDA autocast for memory-efficient full-resolution inference.")
    return parser.parse_args()


def merge_train_args(cli: argparse.Namespace, ckpt: Dict) -> argparse.Namespace:
    args = parse_train_args([])
    ckpt_args = ckpt.get("args", {}) if isinstance(ckpt, dict) else {}
    if isinstance(ckpt_args, dict):
        for key, value in ckpt_args.items():
            if hasattr(args, key):
                setattr(args, key, value)
    args.resume = str(cli.ckpt)
    args.low_root = str(cli.low_root or args.low_root)
    args.gt_root = str(cli.gt_root or args.gt_root)
    args.high_root = str(cli.high_root or args.high_root)
    args.scist_imf_ckpt = str(cli.scist_imf_ckpt or args.scist_imf_ckpt)
    args.scist_priors = str(cli.scist_priors or args.scist_priors)
    if str(cli.scist_ablation or ""):
        args.scist_ablation = str(cli.scist_ablation)
    elif not hasattr(args, "scist_ablation"):
        args.scist_ablation = "full"
    args.batch_size = int(cli.batch_size)
    args.eval_num_workers = int(cli.num_workers)
    args.max_eval_batches = int(cli.max_eval_batches)
    args.gpu = int(cli.gpu)
    args.device = str(cli.device)
    args.scist = 1
    args.stage = "real_adapt"
    args.pin_memory = False
    args.persistent_workers = False
    return args


def ensure_dirs(root: str) -> Dict[str, str]:
    paths = {
        "enhanced": os.path.join(root, "lolv1_test", "enhanced_rgb"),
        "log_gain_raw": os.path.join(root, "lolv1_test", "log_gain_raw"),
        "gain_raw": os.path.join(root, "lolv1_test", "gain_raw"),
        "gain_vis": os.path.join(root, "lolv1_test", "gain_vis"),
        "visual": os.path.join(root, "visual_samples"),
    }
    for path in paths.values():
        os.makedirs(path, exist_ok=True)
    return paths


def write_config(path: str, args: argparse.Namespace, cli: argparse.Namespace) -> None:
    keys = [
        "scist_ablation",
        "resume",
        "low_root",
        "gt_root",
        "high_root",
        "scist_imf_ckpt",
        "scist_priors",
        "batch_size",
        "g_embed_dim",
        "scist_cond_dim",
        "lambda_state",
        "lambda_domain",
        "lambda_illum_smooth",
        "clip_model_name",
        "clip_pretrained",
        "clip_gamma",
        "clip_image_size",
        "gain_min",
        "gain_max",
        "initial_gain",
        "save_random_seed",
    ]
    with open(path, "w", encoding="utf-8") as f:
        f.write("# Generated by scripts/eval_scist_ablation.py\n")
        f.write(f"eval_ckpt: {json.dumps(str(cli.ckpt), ensure_ascii=False)}\n")
        f.write(f"eval_out_dir: {json.dumps(str(cli.out_dir), ensure_ascii=False)}\n")
        for key in keys:
            if hasattr(args, key):
                f.write(f"{key}: {json.dumps(getattr(args, key), ensure_ascii=False)}\n")
        f.write(f"content_bias_suppression: {json.dumps(scist_uses_bias_suppression(args))}\n")
        f.write(f"eval_size: {int(cli.eval_size)}\n")
        f.write(f"preserve_original_size: {json.dumps(int(cli.eval_size) <= 0)}\n")
        f.write(f"eval_amp: {int(cli.eval_amp)}\n")


def selected_samples(dataset: LowLightEvalDataset, sample_ids: str, max_count: int) -> List[str]:
    names = [os.path.basename(pair[0]) for pair in dataset.pairs]
    if sample_ids.strip():
        wanted = {x.strip() for x in sample_ids.split(",") if x.strip()}
        stems = {os.path.splitext(x)[0] for x in wanted}
        return [n for n in names if n in wanted or os.path.splitext(n)[0] in stems]
    return names[: max(0, int(max_count))]


def mean_or_none(vals: List[float]) -> Optional[float]:
    return float(sum(vals) / len(vals)) if vals else None


def fmt(v: Optional[float], decimals: int) -> str:
    if v is None:
        return "NA"
    return f"{float(v):.{int(decimals)}f}"


def build_metrics(device: torch.device):
    try:
        import pyiqa  # type: ignore

        return {
            "psnr": pyiqa.create_metric("psnr", test_y_channel=True, color_space="ycbcr", device=device),
            "ssim": pyiqa.create_metric("ssim", device=device),
            "niqe": pyiqa.create_metric("niqe", device=device),
            "musiq": pyiqa.create_metric("musiq", device=device),
        }
    except Exception as exc:
        print(f"[Warning] pyiqa unavailable, falling back to PSNR/SSIM only if skimage exists: {exc}")
        return {}


def metric_batch(metrics: Dict, enhanced: torch.Tensor, gt: torch.Tensor, compute_no_ref: bool) -> Dict[str, List[Optional[float]]]:
    out: Dict[str, List[Optional[float]]] = {"psnr": [], "ssim": [], "niqe": [], "musiq": []}
    bsz = int(enhanced.shape[0])

    def _expand(vals):
        vals = [float(x) for x in vals]
        if len(vals) == 1 and bsz > 1:
            return vals * bsz
        return vals

    if metrics:
        with torch.no_grad():
            for key in ("psnr", "ssim"):
                val = metrics[key](enhanced, gt)
                vals = val.detach().cpu().view(-1).tolist() if isinstance(val, torch.Tensor) else [float(val)]
                out[key] = _expand(vals)
            if compute_no_ref:
                for key in ("niqe", "musiq"):
                    val = metrics[key](enhanced)
                    vals = val.detach().cpu().view(-1).tolist() if isinstance(val, torch.Tensor) else [float(val)]
                    out[key] = _expand(vals)
            else:
                out["niqe"] = [None for _ in out["psnr"]]
                out["musiq"] = [None for _ in out["psnr"]]
        return out

    try:
        from skimage.metrics import peak_signal_noise_ratio, structural_similarity  # type: ignore
    except Exception:
        return out

    enh_np = enhanced.detach().cpu().numpy()
    gt_np = gt.detach().cpu().numpy()
    for i in range(enh_np.shape[0]):
        e = enh_np[i].transpose(1, 2, 0)
        g = gt_np[i].transpose(1, 2, 0)
        out["psnr"].append(float(peak_signal_noise_ratio(g, e, data_range=1.0)))
        try:
            out["ssim"].append(float(structural_similarity(g, e, data_range=1.0, channel_axis=-1)))
        except Exception:
            out["ssim"].append(None)
        out["niqe"].append(None)
        out["musiq"].append(None)
    return out


@torch.no_grad()
def make_condition(
    args: argparse.Namespace,
    models: Dict[str, torch.nn.Module],
    scist_modules: Dict[str, torch.nn.Module],
    low: torch.Tensor,
    residual: torch.Tensor,
) -> torch.Tensor:
    target_state = None
    if scist_needs_target_state(args):
        target_state = scist_target_state(
            low,
            models["clip"],
            scist_modules["state_extractor"],  # type: ignore[arg-type]
            scist_modules["state_normalizer"],  # type: ignore[arg-type]
            scist_modules["imf"],  # type: ignore[arg-type]
            residual,
            state_min=scist_modules.get("state_min"),  # type: ignore[arg-type]
            state_max=scist_modules.get("state_max"),  # type: ignore[arg-type]
            delta_clip=float(scist_modules.get("delta_clip", getattr(args, "scist_delta_clip", 0.0))),
        )
    if target_state is None:
        target_state = low.new_zeros((int(low.shape[0]), 128))
    cond = prepare_semantic_domain_condition(
        models["clip"],
        models["conditioner"],
        low,
        residual,
        clip_scale=float(args.clip_scale),
        target_state=target_state,
    )
    return apply_scist_condition_mask(cond, args)


def main() -> None:
    cli = parse_args()
    os.makedirs(cli.out_dir, exist_ok=True)
    ckpt = torch.load(cli.ckpt, map_location="cpu")
    train_args = merge_train_args(cli, ckpt)
    device = select_device(train_args)
    print(f"[EvalAblation] variant={scist_ablation_name(train_args)} device={device}")

    resize_size = None if int(cli.eval_size) <= 0 else (int(cli.eval_size), int(cli.eval_size))
    if resize_size is None and int(cli.batch_size) != 1:
        raise ValueError("--batch_size must be 1 when --eval_size=0 because original image sizes may differ.")
    dataset = LowLightEvalDataset(train_args.low_root, train_args.gt_root, resize_size=resize_size)
    loader = DataLoader(dataset, batch_size=int(cli.batch_size), shuffle=False, num_workers=int(cli.num_workers))
    paths = ensure_dirs(cli.out_dir)
    write_config(os.path.join(cli.out_dir, "config.yaml"), train_args, cli)
    fixed_names = selected_samples(dataset, cli.sample_ids, int(cli.save_visual_max))
    with open(os.path.join(cli.out_dir, "visual_sample_ids.json"), "w", encoding="utf-8") as f:
        json.dump({"sample_ids": fixed_names}, f, ensure_ascii=False, indent=2)

    models = build_models(train_args, device=device, in_channels=3)
    load_resume_if_needed(train_args, models, device=device)
    scist_modules = load_scist_modules(train_args, models, device=device)
    residual = ckpt.get("residual")
    if not isinstance(residual, torch.Tensor):
        raise KeyError("Checkpoint does not contain residual; rerun training save or provide a compatible checkpoint.")
    residual = residual.to(device)

    for module in models.values():
        module.eval()

    metrics = build_metrics(device)
    rows = []
    sums: Dict[str, List[float]] = {"psnr": [], "ssim": [], "niqe": [], "musiq": []}
    compute_no_ref = int(cli.skip_no_ref_metrics) <= 0
    log_min = float(np.log(max(1e-6, float(train_args.gain_min))))
    log_max = float(np.log(max(float(train_args.gain_min) + 1e-6, float(train_args.gain_max))))

    for batch_idx, (low, gt, names) in enumerate(loader):
        if int(cli.max_eval_batches) > 0 and batch_idx >= int(cli.max_eval_batches):
            break
        low = low.to(device)
        gt = gt.to(device)
        cond = make_condition(train_args, models, scist_modules, low, residual)
        amp_enabled = device.type == "cuda" and int(cli.eval_amp) > 0
        with torch.autocast(device_type=device.type, dtype=torch.float16, enabled=amp_enabled):
            out = models["model"].training_step(low_img=low, cond=cond, lambda_smooth=0.0)
        enhanced = torch.nan_to_num(out["enhanced"], nan=0.0, posinf=1.0, neginf=0.0).clamp(0.0, 1.0)
        log_gain = torch.nan_to_num(out["log_gain"], nan=0.0, posinf=0.0, neginf=0.0).detach()
        gain = torch.exp(log_gain).detach()

        mb = metric_batch(metrics, enhanced, gt, compute_no_ref=compute_no_ref)
        batch_names = list(names)
        for i, name in enumerate(batch_names):
            stem = os.path.splitext(os.path.basename(str(name)))[0]
            save_image(enhanced[i].detach().cpu(), os.path.join(paths["enhanced"], f"{stem}.png"))
            np.save(os.path.join(paths["log_gain_raw"], f"{stem}.npy"), log_gain[i].detach().cpu().numpy())
            np.save(os.path.join(paths["gain_raw"], f"{stem}.npy"), gain[i].detach().cpu().numpy())
            gain_vis = (log_gain[i : i + 1] - log_min).div(max(1e-6, log_max - log_min)).clamp(0.0, 1.0)
            save_image(gain_vis.detach().cpu(), os.path.join(paths["gain_vis"], f"{stem}_log_gain_vis.png"))

            row = {
                "image": str(name),
                "psnr": mb["psnr"][i],
                "ssim": mb["ssim"][i],
                "niqe": mb["niqe"][i],
                "musiq": mb["musiq"][i],
            }
            rows.append(row)
            for key in sums:
                val = row[key]
                if val is not None:
                    sums[key].append(float(val))

            if str(name) in fixed_names or stem in {os.path.splitext(x)[0] for x in fixed_names}:
                sample_dir = os.path.join(paths["visual"], stem)
                os.makedirs(sample_dir, exist_ok=True)
                save_image(low[i].detach().cpu(), os.path.join(sample_dir, "input.png"))
                save_image(gt[i].detach().cpu(), os.path.join(sample_dir, "gt.png"))
                save_image(enhanced[i].detach().cpu(), os.path.join(sample_dir, f"{scist_ablation_name(train_args)}.png"))
                np.save(os.path.join(sample_dir, f"{scist_ablation_name(train_args)}_A.npy"), log_gain[i].detach().cpu().numpy())
                np.save(os.path.join(sample_dir, f"{scist_ablation_name(train_args)}_G.npy"), gain[i].detach().cpu().numpy())

    csv_path = os.path.join(cli.out_dir, "lolv1_test", "per_image_metrics.csv")
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["image", "psnr", "ssim", "niqe", "musiq"])
        writer.writeheader()
        writer.writerows(rows)

    summary = {
        "variant": scist_ablation_name(train_args),
        "content_bias_suppression": scist_uses_bias_suppression(train_args),
        "eval_size": int(cli.eval_size),
        "preserve_original_size": int(cli.eval_size) <= 0,
        "eval_amp": int(cli.eval_amp),
        "checkpoint": str(cli.ckpt),
        "num_images": len(rows),
        "psnr": mean_or_none(sums["psnr"]),
        "ssim": mean_or_none(sums["ssim"]),
        "niqe": mean_or_none(sums["niqe"]),
        "musiq": mean_or_none(sums["musiq"]),
    }
    with open(os.path.join(cli.out_dir, "lolv1_test", "summary_metrics.json"), "w", encoding="utf-8") as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)
    print(
        "[EvalAblation] "
        f"PSNR={fmt(summary['psnr'], cli.metric_decimals)} "
        f"SSIM={fmt(summary['ssim'], cli.metric_decimals)} "
        f"NIQE={fmt(summary['niqe'], cli.metric_decimals)} "
        f"MUSIQ={fmt(summary['musiq'], cli.metric_decimals)}"
    )


if __name__ == "__main__":
    main()
